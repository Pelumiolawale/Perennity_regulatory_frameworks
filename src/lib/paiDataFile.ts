// ============================================================================
// FMP-ready PAI Data File — SFDR 2022/1288 Annex I Table 1 mirror
// (v0.5.0-alpha.6 — Phase 1, commit 1.4)
// ============================================================================
//
// The F8 deliverable from the May 2026 pressure-test. PB's differentiation
// from Big 4 SPO providers is not narrative quality; it is producing the
// FMP-ready structured deliverable (machine-readable PAI data, structured
// evidence pack, verdict cells) as a first-class output alongside the
// narrative. This file makes that claim true at the code level.
//
// Schema is identical to SFDR 2022/1288 Annex I Table 1 (mandatory indicators).
// Structural identity with the regulation — not a PB schema that maps to it.
// Drop-in for FMP ingestion into existing Art 9 fund PAI portfolio integration.
//
// Row set: PAIs 1, 2, 4, 5, 7, 8, 9, 10, 11, 13 — ten mandatory indicators
// relevant to data-centre projects. PAI 4 (fossil-fuel sector exposure) is
// always emitted as `not_applicable` for DC projects, never omitted —
// drop-in-ready for FMP ingestion requires structural completeness.
//
// No new input collection. Every field derives from existing v3.5 evidence
// inputs on ProjectInput.sfdr (DNSH evidence, Art 9 PAI data) and
// EntityInput.sfdr (governance, PAI disclosures).
// ============================================================================

import type { EngineRun } from "../engine";
import type {
  ProjectDNSHEvidence,
  Art9PAIDataInputs,
  ProjectPAIDatum,
  AssuranceTier,
} from "../sfdr/types";

export interface PAIDataFile {
  schema_source: "SFDR_2022_1288_Annex_I_Table_1";
  reporting_period: string;
  rows: PAIRow[];
}

export type VerificationStatus =
  | "third_party_assured"
  | "management_attested"
  | "unverified"
  | "not_applicable";

export interface PAIRow {
  pai_number: number;
  indicator_name: string;
  metric_definition: string;
  value: number | string | null;
  unit: string;
  data_source: string;
  methodology_note: string;
  verification_status: VerificationStatus;
  applicability: "applicable" | "not_applicable";
  applicability_rationale?: string;
  data_unavailable_rationale?: string;
}

